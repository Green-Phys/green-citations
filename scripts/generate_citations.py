#!/usr/bin/env python3
"""Generate human and machine-readable citation outputs from the authorities."""

from __future__ import annotations

import argparse
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]


def load() -> tuple[dict, dict[str, dict]]:
    policy = yaml.safe_load((ROOT / "CITATIONS.yaml").read_text())
    cff = yaml.safe_load((ROOT / "CITATION.cff").read_text())
    papers: dict[str, dict] = {}
    for paper in cff.get("references", []):
        keys = [item["value"] for item in paper.get("identifiers", []) if item["type"] == "other"]
        if len(keys) != 1:
            raise ValueError("each reference must have exactly one canonical 'other' identifier")
        if keys[0] in papers:
            raise ValueError(f"duplicate publication key: {keys[0]}")
        papers[keys[0]] = paper
    return policy, papers


def cited_keys(policy: dict) -> set[str]:
    keys: set[str] = set()
    for component in policy["components"].values():
        keys.update(component["implementation"])
        keys.update(component.get("historical", []))
        for mapping in (component["versions"], component["methods"]):
            for values in mapping.values():
                keys.update(values)
    return keys


def author_text(paper: dict) -> str:
    return ", ".join(
        f'{author.get("given-names", "")} {author["family-names"]}'.strip()
        for author in paper["authors"]
    )


def reference_text(paper: dict) -> str:
    volume = f' {paper["volume"]}' if "volume" in paper else ""
    return (
        f'{author_text(paper)}. “{paper["title"]}.” '
        f'*{paper["journal"]}*{volume} ({paper["year"]}), {paper["start"]}. '
        f'https://doi.org/{paper["doi"]}'
    )


def markdown(policy: dict, papers: dict[str, dict]) -> str:
    lines = [
        "# Citing GREEN",
        "",
        "<!-- Generated by scripts/generate_citations.py; do not edit. -->",
        "",
        f'Policy status: **{policy["policy-status"]}**.',
        "",
        policy["policy-note"],
        "",
    ]
    for slug, component in policy["components"].items():
        lines += [f'## {component["name"]} (`{slug}`)', "", "### Implementation", ""]
        for key in component["implementation"]:
            paper = papers[key]
            lines.append(f"- {reference_text(paper)}")
        if component.get("historical"):
            lines += ["", "### Historical and optional", ""]
            for key in component["historical"]:
                lines.append(f"- {reference_text(papers[key])}")
        if component["versions"]:
            lines += ["", "### Versions", ""]
        for version, keys in component["versions"].items():
            lines.append(f"#### Version {version}")
            lines.append("")
            for key in keys:
                lines.append(f"- {reference_text(papers[key])}")
        lines += ["", "### Scientific methods", "", f'Status: **{component["method-mapping-status"]}**.']
        if component.get("method-mapping-note"):
            lines += ["", component["method-mapping-note"]]
        for method, keys in component["methods"].items():
            lines.append(f'- {method}: ' + ", ".join(f'`{key}`' for key in keys))
        lines.append("")
    return "\n".join(lines)


def bibtex(papers: dict[str, dict]) -> str:
    entries = []
    for key, paper in papers.items():
        fields = {
            "title": "{" + paper["title"] + "}",
            "author": " and ".join(f'{a["family-names"]}, {a.get("given-names", "")}' for a in paper["authors"]),
            "journal": paper["journal"],
            "year": str(paper["year"]),
            "doi": paper["doi"],
            "pages": paper["start"],
        }
        if "volume" in paper:
            fields["volume"] = str(paper["volume"])
        body = ",\n".join(f"  {name} = {{{value}}}" for name, value in fields.items())
        entries.append(f"@article{{{key},\n{body}\n}}")
    return "\n\n".join(entries) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    policy, papers = load()
    unknown = cited_keys(policy) - papers.keys()
    if unknown:
        raise ValueError(f"unknown publication keys: {sorted(unknown)}")
    outputs = {"CITATION.md": markdown(policy, papers), "references.bib": bibtex(papers)}
    for name, content in outputs.items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"generated file is stale: {name}")
        else:
            path.write_text(content)


if __name__ == "__main__":
    main()

